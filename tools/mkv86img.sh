#!/bin/bash
# Build the disk images for the v86 browser host.
#
# Produces two files in web/images/:
#   boot.img     1.44MB bootable FreeDOS floppy, with our AUTOEXEC
#   dosypp.img   32MB FAT16 hard disk holding DOSYPP.EXE and friends
#
# Why two: making a FAT16 hard disk bootable needs DOS's own SYS command, so
# instead we boot an unmodified FreeDOS floppy and keep everything on a roomy
# C:. That also matches how a period machine was actually set up, and means
# the data image can be rebuilt without touching the boot media.
#
# Needs mtools (brew install mtools).
set -euo pipefail

# Nothing in here may ever ask a question.
#
# mtools prompts on a name clash -- mmd on a directory that exists reads
# stdin for an answer -- and with 2>/dev/null the question is invisible.
# Run from a script with stdin redirected it gets EOF and carries on; run
# by a person in a terminal it waits for ever, printing nothing. Every
# automated run of this passed for months while `make pages` hung at the
# same line for anybody watching.
exec < /dev/null

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IMAGES="$ROOT/web/images"
CACHE="${DOSYPP_CACHE:-$ROOT/.cache}"
DOS_SRC="$ROOT/dosbox-x/c"

BOOT_IMG="$IMAGES/boot.img"
DATA_IMG="$IMAGES/dosypp.img"
# 128MB rather than 64: the browser demo downloads a game and unzips it,
# and the game is now Doom -- 7.6MB of zip that unpacks to 19MB, on top of
# the packages already staged here. v86 fetches the image in blocks over
# HTTP Range, so the size costs load time only for the blocks actually
# touched; what it does cost is the published artifact, which is why this
# is 128 and not 512.
DATA_MB="${DATA_MB:-128}"

# FreeDOS 1.3 does not publish a standalone boot floppy any more; the 1.44MB
# bootable image lives inside the Floppy Edition archive as 144m/x86BOOT.img.
FREEDOS_URL="${FREEDOS_URL:-https://www.ibiblio.org/pub/micro/pc-stuff/freedos/files/distributions/1.3/official/FD13-FloppyEdition.zip}"
FREEDOS_MEMBER="144m/x86BOOT.img"

die() { echo "error: $*" >&2; exit 1; }

command -v mcopy >/dev/null 2>&1 || die "mtools not found (brew install mtools)"

mkdir -p "$IMAGES" "$CACHE"

# mtools refuses to touch raw images without this, and we do not want to
# depend on the user's ~/.mtoolsrc.
export MTOOLS_SKIP_CHECK=1

# ---------------------------------------------------------------- boot image

if [ ! -f "$CACHE/x86BOOT.img" ]; then
    if [ ! -f "$CACHE/FD13-FloppyEdition.zip" ]; then
        echo "fetching FreeDOS 1.3 Floppy Edition (~21MB)..."
        curl -fsSL "$FREEDOS_URL" -o "$CACHE/FD13-FloppyEdition.zip.part"
        mv "$CACHE/FD13-FloppyEdition.zip.part" "$CACHE/FD13-FloppyEdition.zip"
    fi
    command -v unzip >/dev/null 2>&1 || die "unzip not found"
    unzip -o -q -j "$CACHE/FD13-FloppyEdition.zip" "$FREEDOS_MEMBER" -d "$CACHE"
    [ -f "$CACHE/x86BOOT.img" ] || die "could not extract $FREEDOS_MEMBER"
fi

cp "$CACHE/x86BOOT.img" "$BOOT_IMG"

# Replace the installer's startup with ours. FD13BOOT boots into the FreeDOS
# installer otherwise, which is not what we want.
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

cat > "$TMP/FDAUTO.BAT" <<'EOF'
@echo off
set DOSDIR=A:\FREEDOS
path A:\BIN;C:\
echo.
echo  DOSy++ browser host
echo.
if exist C:\GO.BAT goto gotdisk
echo  !! No C: drive found -- is dosypp.img attached as hda?
goto done
:gotdisk
c:
call C:\GO.BAT
:done
EOF

mcopy -i "$BOOT_IMG" -o "$TMP/FDAUTO.BAT" ::FDAUTO.BAT
echo "boot.img:  FreeDOS floppy with our FDAUTO.BAT"

# ---------------------------------------------------------------- data image

# Plain FAT16, no partition table: v86 is happy with a superfloppy-style hda
# and it keeps this script free of fdisk games.
rm -f "$DATA_IMG"
mformat -i "$DATA_IMG" -C -T $((DATA_MB * 1024 * 1024 / 512)) -h 16 -s 63 \
        -v DOSYPP ::

copy_in() {
    local src="$1" name="$2" required="$3"
    if [ -f "$src" ]; then
        mcopy -i "$DATA_IMG" -o "$src" "::$name"
        printf '  + %-14s %s\n' "$name" "$(du -h "$src" | cut -f1)"
    elif [ "$required" = "yes" ]; then
        die "missing $src
       $name is required. See docs/V86.md."
    else
        printf '  - %-14s (absent, see docs/V86.md)\n' "$name"
    fi
}

echo "dosypp.img: ${DATA_MB}MB FAT16"

# Built by `make dos` (or tools/dosmake.sh).
copy_in "$ROOT/build/dos/DOSYPP.EXE" DOSYPP.EXE no

# DPMI host, ships with DJGPP. Required at runtime by anything DJGPP builds.
copy_in "$DOS_SRC/CWSDPMI.EXE" CWSDPMI.EXE no

# v86 emulates an RTL8029 (PCI NE2000), so the guest needs Realtek's PCI
# packet driver -- NOT the ISA NE2000.COM used on real hardware and in
# DOSBox-X, which cannot find a PCI card.
copy_in "$DOS_SRC/PCIPKT.COM" PCIPKT.COM no

# The tune, so the browser demo has music. Generated by make modules.
copy_in "$ROOT/art/DOSYPP.MOD" DOSYPP.MOD no

# Drives the MPU-401 directly: what a game does when you pick "Roland".
# v86 answers the probe and throws the notes away, so the page taps the
# port and plays them itself (web/midi.mjs). This is what the browser MIDI
# gate runs. Built by make dos-midi-any.
copy_in "$ROOT/build/dos/MIDITEST.EXE" MIDITEST.EXE no

# v86 gets its OWN WATTCP.CFG, static rather than DHCP.
#
# The DOSBox-X config uses DHCP because slirp hands out leases. v86's Wisp
# adapter also answers DHCP in JavaScript, but Watt-32 does not accept its
# offer (observed: "Configuring through DHCP..failed" with the packet driver
# loaded and working). Since v86's addressing is fixed and documented --
# guest 192.168.86.100, router 192.168.86.1 -- static configuration is both
# deterministic and faster to boot, so there is nothing to miss here.
cat > "$TMP/WATTCP.CFG" <<'EOF'
# Watt-32 configuration for the v86 browser host.
#
# Static on purpose: v86's virtual router hands out these exact addresses,
# and Watt-32 does not take its DHCP offer. Do not "fix" this to dhcp.
my_ip      = 192.168.86.100
netmask    = 255.255.255.0
gateway    = 192.168.86.1
nameserver = 192.168.86.1

domain.suffix = lan
EOF
mcopy -i "$DATA_IMG" -o "$TMP/WATTCP.CFG" ::WATTCP.CFG
echo "  + WATTCP.CFG    (static, 192.168.86.100)"

cat > "$TMP/GO.BAT" <<'EOF'
@echo off
rem DOSy++ startup for the v86 browser host.
rem
rem BLASTER is how every DOS program finds a Sound Blaster, and DOS does
rem not set it -- the card's own driver normally does. v86 emulates an
rem SB16 at the standard address, so this is the standard line. Without
rem it DOSy++ reports "BLASTER is not set" and runs silently.
SET BLASTER=A220 I5 D1 H5 T6
rem
rem UNZIP complains "TZ environment variable not found" on every file it
rem extracts otherwise. It is only a warning, and it is only noise.
SET TZ=UTC0
rem
rem DOS has no mouse. Games that want one do not politely do without it:
rem BLKDROP exits with "Fatal Error #243: mouse driver failure". CTMOUSE
rem provides int 33h, and v86's emulated PS/2 mouse is bound to the page.
if exist CTMOUSE.EXE CTMOUSE > NUL
rem
rem v86's NIC is a PCI RTL8029, so Realtek's PCIPKT is the right driver --
rem the ISA NE2000.COM used elsewhere cannot find a PCI card. PCIPKT probes
rem the bus itself, so only the software interrupt needs specifying.
if not exist PCIPKT.COM goto nodrv
echo  Loading RTL8029 packet driver...
PCIPKT 0x60
echo.
rem The relay maps 10.77.0.1 to whatever hub it was started with, so the
rem guest never needs to know the real address -- and needs no DNS.
echo  Starting DOSy++ ...
rem No -n: the client asks for a handle on its first run and offers the
rem one in DOSYPP.INI as the default, which is one keypress away. Passing
rem -n here would answer the question before it was asked.
DOSYPP.EXE 10.77.0.1
goto run
:nodrv
echo  !! PCIPKT.COM missing -- no network. See docs/PKTDRV.md.
:run
echo.
echo  Type  DOSYPP 10.77.0.1  to reconnect, or EXIT for a prompt.
echo  Downloaded something? Try:  PLAY BLKDROP   or   PLAY BOOM
echo  (BOOM is Doom -- its music comes out of the MPU-401, and the
echo   browser plays it if you pressed Enable MIDI on the page.)
echo.
EOF
mcopy -i "$DATA_IMG" -o "$TMP/GO.BAT" ::GO.BAT
echo "  + GO.BAT"

# Non-interactive variant for the headless Node harness: same thing, but
# everything goes to COM1 so v86 can capture it without screen scraping.
cat > "$TMP/AUTOTEST.BAT" <<'EOF'
@echo off
SET BLASTER=A220 I5 D1 H5 T6
PCIPKT 0x60 > COM1
DOSYPP.EXE --batch -p 1511 10.77.0.1 > COM1
echo AUTOTEST-DONE > COM1
EOF
mcopy -i "$DATA_IMG" -o "$TMP/AUTOTEST.BAT" ::AUTOTEST.BAT
echo "  + AUTOTEST.BAT"

# ------------------------------------------------- a share worth browsing
#
# Two small files so the browser demo has something in its share door, and
# so the transfer gate has something to move. Deliberately small: hashing
# happens inside an emulator in a browser tab, and 96KB takes no time at
# all even there. A "pre-hashed" cache was the other option and does not
# work -- the hash cache keys on local paths, which differ between the
# machine that built the image and the guest that reads it.
#
# Deterministic content, so the TTH is the same every build and a failure
# is reproducible.
# Every directory this script makes, so none is asked for twice.
MADE_DIRS="DL"
mmd -i "$DATA_IMG" ::DL 2>/dev/null || true
python3 - "$TMP" <<'PY'
import sys, os, random
tmp = sys.argv[1]
for name, size, seed in [("DEMO1.BIN", 64 * 1024, 1994),
                         ("DEMO2.BIN", 32 * 1024, 1995)]:
    random.seed(seed)
    with open(os.path.join(tmp, name), "wb") as f:
        f.write(bytes(random.getrandbits(8) for _ in range(size)))
PY
mcopy -i "$DATA_IMG" -o "$TMP/DEMO1.BIN" ::DL/DEMO1.BIN
mcopy -i "$DATA_IMG" -o "$TMP/DEMO2.BIN" ::DL/DEMO2.BIN
echo "  + DL\\DEMO1.BIN  64K"
echo "  + DL\\DEMO2.BIN  32K"

# Real DOS software, if tools/fetchatmos.sh has fetched any. The browser
# demo is where this matters most: somebody who opens the page and presses
# 5 should see software, not DEMO1.BIN and DEMO2.BIN.
#
# Size-capped rather than curated: the image is 32MB and FreeDoom alone is
# 26, so anything over a couple of megabytes stays out and the budget stops
# the rest. The two demo files remain either way -- the transfer gate
# fetches DEMO1.BIN by name.
ATMOS="${ATMOS_DIR:-$ROOT/build/atmos}"
if [ -d "$ATMOS" ]; then
    budget=$((12 * 1024 * 1024))
    added=0

    while IFS= read -r f; do
        sz=$(wc -c < "$f" | tr -d ' ')
        [ "$sz" -gt $((2500 * 1024)) ] && continue
        [ "$sz" -gt "$budget" ] && continue

        rel="${f#$ATMOS/}"
        dir="DL/$(dirname "$rel")"
        [ "$(dirname "$rel")" = "." ] && dir="DL"

        # One level at a time: mmd does not create parents, so asking for
        # DL/WAREZ/APPS before DL/WAREZ exists fails quietly and the file
        # with it -- which is how eight of eleven packages went missing
        # from the image while the script reported success.
        #
        # And once each: mmd on a directory that already exists is a name
        # clash, which mtools asks about. Remembering what has been made
        # means the question never comes up, which is a better fix than
        # being able to survive it.
        acc=""
        for part in $(echo "$dir" | tr '/' ' '); do
            acc="${acc:+$acc/}$part"
            case " $MADE_DIRS " in
                *" $acc "*) continue ;;
            esac
            mmd -i "$DATA_IMG" "::$acc" 2>/dev/null || true
            MADE_DIRS="$MADE_DIRS $acc"
        done
        mcopy -i "$DATA_IMG" -o "$f" "::$dir/$(basename "$rel")" || continue

        budget=$((budget - sz))
        added=$((added + 1))
        printf '  + DL\\%-22s %s\n' "$rel" \
            "$(echo "$sz" | awk '{printf "%.1fM", $1/1048576}')"
    done <<EOF
$(find "$ATMOS" -type f | sort)
EOF

    echo "  ($added real packages from $ATMOS -- see tools/fetchatmos.sh)"
else
    echo "  (no real software: run tools/fetchatmos.sh for the demo share)"
fi

# The share, and an active listen port: the browser guest can dial out
# through the relay but nothing can dial in, so an upload only happens when
# the guest is the side doing the dialling -- which is what an ACTIVE
# downloader's CTM asks of it. Hence active = no here: we are the uploader
# and we wait to be told where to dial.
cat > "$TMP/DOSYPP.INI" <<'EOF'
; DOSy++ settings for the v86 browser host.
;
; The hub address is the relay's sentinel: 10.77.0.1 is whatever hub the
; relay was started with. No DNS is involved anywhere in this path.
hub        = 10.77.0.1
port       = 1511
nick       = WebNode
description = in a browser tab
share      = C:\DL
sound      = no

;
; The tune, through v86's emulated Sound Blaster 16. There is no OPL in
; v86, so FM music would be silent -- but this mixer produces PCM and
; feeds it over DMA, which v86 does emulate.
;
; 22050 rather than the 11025 a real 486 gets. The mixer costs about 5.7%
; of a 486DX2-66 at 11kHz (make dos-bench-run), so twice the rate is
; roughly twice that -- which a real 486 sharing its time with hashing and
; a network does not have to spare, and the machine under a browser tab
; does. The v86 sound gate measures what the mixer actually delivers here
; rather than assuming it keeps up.
music      = yes
music.file = DOSYPP.MOD
music.rate = 22050

; Passive. A browser guest cannot be dialled -- Wisp carries outbound
; streams only -- so being honest about that is what makes transfers work:
; an active peer sends us a CTM and we dial it.
active     = no

; The hub-list door (0), pointed at this demo's own list.
;
; The built-in default is a real public service somebody else pays for
; (HUBLIST_DEFAULT_URL in src/adc/hublist.h). That is the right default for
; a copy of this on a real machine, and the wrong one for a demo strangers
; open: it would point all of them at hubs that never agreed to be part of
; this. 10.77.0.3 is a sentinel the relay maps to a one-entry list served
; beside the demo hub -- see tools/mkhublist.py.
;
; The relay is an allowlist either way, so an unmapped address simply
; cannot be reached. This makes the door honest rather than merely
; harmless.
hublist    = http://10.77.0.3/hublist.xml.bz2
EOF
mcopy -i "$DATA_IMG" -o "$TMP/DOSYPP.INI" ::DOSYPP.INI
echo "  + DOSYPP.INI    (share C:\\DL, passive)"

# The transfer gate's batch file: log in, hash the two demo files, and stay
# up long enough to serve them. Everything to COM1 for the harness.
cat > "$TMP/AUTOXFER.BAT" <<'EOF'
@echo off
SET BLASTER=A220 I5 D1 H5 T6
PCIPKT 0x60 > COM1
DOSYPP.EXE --null-display --door 5 --peer-trace --run-secs 200 10.77.0.1 > COM1
echo AUTOXFER-DONE > COM1
EOF
mcopy -i "$DATA_IMG" -o "$TMP/AUTOXFER.BAT" ::AUTOXFER.BAT
echo "  + AUTOXFER.BAT"

# The hub-list gate: does door 0 show this demo's own hub, and does the
# guest try to reach anything that was not mapped for it?
cat > "$TMP/AUTOHUBL.BAT" <<'EOF'
@echo off
PCIPKT 0x60 > COM1
DOSYPP.EXE --null-display --screenshot HL.TXT --door 10 --fetch-hublist --run-secs 40 10.77.0.1 > COM1
echo AUTOHUBL-DONE > COM1
EOF
mcopy -i "$DATA_IMG" -o "$TMP/AUTOHUBL.BAT" ::AUTOHUBL.BAT
echo "  + AUTOHUBL.BAT  (the hub list, and nobody else's hubs)"

# The sound gate: does the Sound Blaster path work inside v86? The client
# reports what the card has played and what the mixer has fed it, and the
# harness reads both off COM1 -- there is no speaker in Node, but the DMA
# controller's count register does not care.
# The download gate, and the demo flow in one file: search the hub for a
# real game, queue it, let the client verify it against the hash the hub
# advertised, then unpack it and show what came out. Everything to COM1.
#
# This is the claim the browser demo makes, so it is the claim with a rig
# behind it: a DOS binary in a browser engine downloading a game over ADC
# and ending up with its executable on disk.
cat > "$TMP/AUTODL.BAT" <<'EOF'
@echo off
SET BLASTER=A220 I5 D1 H5 T6
PCIPKT 0x60 > COM1
DOSYPP.EXE --null-display --screenshot DL.TXT --door 4 --peer-trace --search BLKDROP --queue --run-secs 150 10.77.0.1 > COM1
echo AUTODL-GOT > COM1
dir BLKDROP.ZIP > COM1
if not exist BLKDROP.ZIP goto done
UNZIP -o -q BLKDROP.ZIP > COM1
dir GAMES\BLKDROP > COM1
:done
echo AUTODL-DONE > COM1
EOF
mcopy -i "$DATA_IMG" -o "$TMP/AUTODL.BAT" ::AUTODL.BAT
echo "  + AUTODL.BAT    (search, download, verify, unzip)"

# The browser MIDI gate: write MIDI to the MPU-401 and let the page's tap
# collect it. The guest cannot tell whether anything is listening -- which
# is the point, since in v86 nothing is until web/midi.mjs attaches.
cat > "$TMP/AUTOMIDI.BAT" <<'EOF'
@echo off
MIDITEST.EXE > COM1
echo AUTOMIDI-DONE > COM1
EOF
mcopy -i "$DATA_IMG" -o "$TMP/AUTOMIDI.BAT" ::AUTOMIDI.BAT
echo "  + AUTOMIDI.BAT  (MIDI out of the emulated MPU-401)"

cat > "$TMP/AUTOSND.BAT" <<'EOF'
@echo off
SET BLASTER=A220 I5 D1 H5 T6
PCIPKT 0x60 > COM1
DOSYPP.EXE --null-display --door 7 --music-report --screenshot SND.TXT --run-secs 40 10.77.0.1 > COM1
echo AUTOSND-DONE > COM1
EOF
mcopy -i "$DATA_IMG" -o "$TMP/AUTOSND.BAT" ::AUTOSND.BAT
echo "  + AUTOSND.BAT   (the Sound Blaster, in a browser engine)"

ATMOS="${ATMOS_DIR:-$ROOT/build/atmos}"

# ------------------------------------------------- opening what you fetch
#
# UNZIP.EXE at the root, because the whole point of the browser demo is
# that you download a game over a real hub and then play it. Taken out of
# the FreeDOS archiver package rather than fetched separately.
UNZIP_SRC="$ATMOS/WAREZ/APPS/UNZIP.ZIP"
if [ -f "$UNZIP_SRC" ]; then
    rm -rf "$TMP/unz"; mkdir -p "$TMP/unz"
    if unzip -o -q -j "$UNZIP_SRC" "BIN/UNZIP.EXE" -d "$TMP/unz" \
            2>/dev/null; then
        mcopy -i "$DATA_IMG" -o "$TMP/unz/UNZIP.EXE" ::UNZIP.EXE
        echo "  + UNZIP.EXE     (opens what the demo downloads)"
    fi
fi

# Boom's config, with its music turned on.
#
# BOOM.CFG ships with music_card = -1, autodetect, and autodetect inside
# v86 finds the SB16 and picks an FM device v86 does not implement -- so
# Doom plays in silence and nothing says why. 6 is MIDI_MPU in Allegro 3's
# driver numbering, which makes it write MIDI to 0x330, where the page is
# listening (web/midi.mjs). Measured: 1,166 notes in 75 seconds
# (make test-v86-doom).
#
# Generated from the fetched package rather than committed, so it stays
# the package's own config with one number changed.
BOOM_ZIP="$ATMOS/WAREZ/GAMES/BOOM.ZIP"
if [ -f "$BOOM_ZIP" ]; then
    rm -rf "$TMP/boom"; mkdir -p "$TMP/boom"
    if unzip -o -q -j "$BOOM_ZIP" "GAMES/BOOM/BOOM.CFG" -d "$TMP/boom" \
            2>/dev/null; then
        python3 - "$TMP/boom/BOOM.CFG" <<'PY'
import re, sys
p = sys.argv[1]
s = open(p, "r", errors="replace").read()
s, n = re.subn(r"^music_card\s+-?\d+", "music_card                    6",
               s, flags=re.M)
open(p, "w").write(s)
sys.exit(0 if n == 1 else f"music_card not found in {p}")
PY
        if [ $? -eq 0 ]; then
            mcopy -i "$DATA_IMG" -o "$TMP/boom/BOOM.CFG" ::BOOMMIDI.CFG
            echo "  + BOOMMIDI.CFG  (Doom's music through the MPU-401)"
        fi
    fi
fi

# A mouse driver, because DOS does not have one.
#
# Plenty of DOS games ask for int 33h and refuse to start without it --
# BLKDROP says "unable to find the mouse. it is really necessary." and
# dies with Fatal Error #243. v86 emulates a PS/2 mouse and the page binds
# it to the screen, so all that was missing was the driver. CuteMouse is
# 6KB and GPL.
CTM_SRC="$ATMOS/WAREZ/APPS/CTMOUSE.ZIP"
if [ -f "$CTM_SRC" ]; then
    rm -rf "$TMP/ctm"; mkdir -p "$TMP/ctm"
    if unzip -o -q -j "$CTM_SRC" "BIN/CTMOUSE.EXE" -d "$TMP/ctm" \
            2>/dev/null; then
        mcopy -i "$DATA_IMG" -o "$TMP/ctm/CTMOUSE.EXE" ::CTMOUSE.EXE
        echo "  + CTMOUSE.EXE   (int 33h, which games insist on)"
    fi
fi

# PLAY.BAT: unzip whatever was downloaded and run what comes out.
#
# The games in the FreeDOS repositories unpack to GAMES/<NAME>/<NAME>.EXE,
# so the batch knows where to look rather than making the user find it.
cat > "$TMP/PLAY.BAT" <<'EOF'
@echo off
if "%1"=="" goto usage
if not exist %1.ZIP goto nozip
echo  Unpacking %1.ZIP ...
UNZIP -o -q %1.ZIP
rem Boom's own config autodetects its music device and gets that wrong
rem inside v86: it picks an FM chip the emulator does not have and plays
rem in silence. BOOMMIDI.CFG is the same file with music_card = 6, which
rem is the MPU-401 -- and this page is listening to that port.
if not exist BOOMMIDI.CFG goto nocfg
if not exist GAMES\%1\BOOM.CFG goto nocfg
echo  Setting %1 to play its music through the MPU-401 ...
copy BOOMMIDI.CFG GAMES\%1\BOOM.CFG > NUL
:nocfg
if exist GAMES\%1\%1.EXE goto run
if exist %1.EXE goto runhere
echo  Unpacked, but no %1.EXE turned up. Look in GAMES\ yourself.
goto done
:run
cd GAMES\%1
%1
cd \
goto done
:runhere
%1
goto done
:nozip
echo  No %1.ZIP here. Download one with DOSYPP first, then try again.
goto done
:usage
echo  PLAY ^<NAME^>   -- unzip NAME.ZIP and run it. Try: PLAY BLKDROP
:done
EOF
mcopy -i "$DATA_IMG" -o "$TMP/PLAY.BAT" ::PLAY.BAT
echo "  + PLAY.BAT      (PLAY BLKDROP unzips and runs it)"

echo
echo "contents of C::"
mdir -i "$DATA_IMG" ::
echo
echo "next: tools/wisprelay.py, then open http://127.0.0.1:8086/"

#!/usr/bin/env python3
"""Generate src/ui/cp437_table.h.

Two tables, both derived from Python's own cp437 codec rather than typed out:

  CP437_TO_UCS[256]   CP437 byte -> Unicode code point. The host backend
                      needs it to draw our screen in a UTF-8 terminal.
  Reverse map         Unicode -> CP437 byte, for the characters a hub can
                      realistically send: Latin-1, common punctuation, and
                      the box/shade glyphs.
"""
import sys

# DOS text mode displays 0x00-0x1F and 0x7F as GLYPHS, not control codes --
# that is where ► ▲ ♦ ♪ live, and screen.h names several of them. Python's
# cp437 codec maps them to U+0001..U+001F instead, so override that range by
# hand from the IBM PC character set.
LOW_GLYPHS = {
    0x00: 0x0020, 0x01: 0x263A, 0x02: 0x263B, 0x03: 0x2665, 0x04: 0x2666,
    0x05: 0x2663, 0x06: 0x2660, 0x07: 0x2022, 0x08: 0x25D8, 0x09: 0x25CB,
    0x0A: 0x25D9, 0x0B: 0x2642, 0x0C: 0x2640, 0x0D: 0x266A, 0x0E: 0x266B,
    0x0F: 0x263C, 0x10: 0x25BA, 0x11: 0x25C4, 0x12: 0x2195, 0x13: 0x203C,
    0x14: 0x00B6, 0x15: 0x00A7, 0x16: 0x25AC, 0x17: 0x21A8, 0x18: 0x2191,
    0x19: 0x2193, 0x1A: 0x2192, 0x1B: 0x2190, 0x1C: 0x221F, 0x1D: 0x2194,
    0x1E: 0x25B2, 0x1F: 0x25BC, 0x7F: 0x2302,
}

rows = []
for b in range(256):
    if b in LOW_GLYPHS:
        rows.append((b, LOW_GLYPHS[b]))
    else:
        rows.append((b, ord(bytes([b]).decode('cp437'))))

# Reverse: only codepoints that round-trip, so we never claim a mapping the
# forward table disagrees with. Skip the low glyph range -- we do not want a
# hub sending U+2192 to become byte 0x1A, which some paths treat as EOF.
rev = {}
for b, cp in rows:
    if b >= 0x20 and b != 0x7F:
        rev.setdefault(cp, b)

# Transliterations for accented Latin that CP437 lacks: fall back to the base
# letter rather than '?'. A filename reading "Bjork" beats "Bj?rk".
TRANSLIT = {
    0x100: 'A', 0x101: 'a', 0x102: 'A', 0x103: 'a', 0x104: 'A', 0x105: 'a',
    0x106: 'C', 0x107: 'c', 0x10C: 'C', 0x10D: 'c', 0x10E: 'D', 0x10F: 'd',
    0x110: 'D', 0x111: 'd', 0x112: 'E', 0x113: 'e', 0x118: 'E', 0x119: 'e',
    0x11A: 'E', 0x11B: 'e', 0x11E: 'G', 0x11F: 'g', 0x12A: 'I', 0x12B: 'i',
    0x130: 'I', 0x131: 'i', 0x139: 'L', 0x13A: 'l', 0x141: 'L', 0x142: 'l',
    0x143: 'N', 0x144: 'n', 0x147: 'N', 0x148: 'n', 0x14C: 'O', 0x14D: 'o',
    0x150: 'O', 0x151: 'o', 0x154: 'R', 0x155: 'r', 0x158: 'R', 0x159: 'r',
    0x15A: 'S', 0x15B: 's', 0x15E: 'S', 0x15F: 's', 0x160: 'S', 0x161: 's',
    0x162: 'T', 0x163: 't', 0x164: 'T', 0x165: 't', 0x16A: 'U', 0x16B: 'u',
    0x16E: 'U', 0x16F: 'u', 0x170: 'U', 0x171: 'u', 0x178: 'Y', 0x179: 'Z',
    0x17A: 'z', 0x17B: 'Z', 0x17C: 'z', 0x17D: 'Z', 0x17E: 'z',
    # Punctuation a modern client will happily send into a 1994 screen.
    0x2018: "'", 0x2019: "'", 0x201A: "'", 0x201C: '"', 0x201D: '"',
    0x201E: '"', 0x2013: '-', 0x2014: '-', 0x2026: '.', 0x2022: '*',
    0x00A0: ' ', 0x200B: '', 0x2039: '<', 0x203A: '>', 0x02DC: '~',
}

out = []
out.append("""/* cp437_table.h - generated by tools/gen_cp437.py, do not edit.
 *
 * Derived from Python's cp437 codec rather than typed by hand: a wrong
 * glyph here is invisible until someone's filename renders as line noise.
 */
#ifndef DOSYPP_CP437_TABLE_H
#define DOSYPP_CP437_TABLE_H

/* CP437 byte -> Unicode code point. The host backend uses this to draw the
   screen in a UTF-8 terminal; on DOS the bytes go to video memory as-is. */
static const unsigned short CP437_TO_UCS[256] = {""")

for i in range(0, 256, 8):
    chunk = rows[i:i+8]
    out.append("    " + " ".join("0x%04X," % cp for _, cp in chunk) +
               "   /* 0x%02X */" % i)
out.append("};\n")

out.append("""/* Unicode -> CP437, for what a hub realistically sends. Sorted by code
   point so lookup can binary-search. Entries with byte 0 mean "drop it". */
typedef struct {
    unsigned short ucs;
    unsigned char  cp437;
} cp437_rev_entry;

static const cp437_rev_entry CP437_FROM_UCS[] = {""")

entries = {}
for cp, b in rev.items():
    if cp >= 0x80:            # ASCII needs no table
        entries[cp] = b
for cp, s in TRANSLIT.items():
    if cp not in entries:
        entries[cp] = ord(s) if s else 0

for cp in sorted(entries):
    out.append("    { 0x%04X, 0x%02X }," % (cp, entries[cp]))

out.append("};\n")
out.append("#define CP437_FROM_UCS_COUNT "
           "(sizeof CP437_FROM_UCS / sizeof CP437_FROM_UCS[0])\n")
out.append("#endif /* DOSYPP_CP437_TABLE_H */")

open('src/ui/cp437_table.h', 'w').write("\n".join(out) + "\n")
print("wrote src/ui/cp437_table.h:", len(entries), "reverse entries")
